# -*- coding: utf-8 -*-
"""
Luna plugin builder.

1. compiles the unmodified friso C sources + freestanding shim into luna.wasm
   (zig cc, wasm32-freestanding, no WASI)
2. packs the friso dictionary (+ patched wordfreq.ini) into assets/dict.pack
3. emits luna-assets.js: base64 wasm + dict pack + neutral3322 Markov model,
   so the plugin also runs straight from file:// (fetch is blocked there)

Run:  python build.py
"""
import base64
import os
import re
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FRISO_ROOT = r'C:\Users\Nope\Desktop\TinyStories-Zh-2M\friso'
DICT_DIR = os.path.join(FRISO_ROOT, 'vendors', 'dict', 'UTF-8')
MODEL_BIN = os.path.normpath(os.path.join(HERE, '..', '..', 'models', 'luna',
                                          'markov_neutral3322.bin'))

SRC_DIR = os.path.join(HERE, 'src')
SHIM_DIR = os.path.join(HERE, 'shim')
INC_DIR = os.path.join(SHIM_DIR, 'include')
ASSET_DIR = os.path.join(HERE, 'assets')

WASM_OUT = os.path.join(HERE, 'luna.wasm')
PACK_OUT = os.path.join(ASSET_DIR, 'dict.pack')
JS_OUT = os.path.join(HERE, 'luna-assets.js')

FRISO_C = [
    'friso.c', 'friso_lexicon.c', 'friso_hash.c', 'friso_array.c',
    'friso_link.c', 'friso_string.c', 'friso_UTF8.c', 'friso_GBK.c',
    'friso_ctype.c',
]
EXPORTS = ['luna_load_pack', 'luna_init', 'luna_segment',
           'luna_buf', 'luna_buf_free', 'luna_dic_size', 'luna_dic_has',
           'luna_cfg_field']


def build_wasm():
    os.makedirs(os.path.dirname(WASM_OUT), exist_ok=True)
    cmd = [
        sys.executable, '-m', 'ziglang', 'cc',
        '--target=wasm32-freestanding',
        '-Oz', '-std=c99', '-w',
        '-fno-builtin',
        '-I', INC_DIR, '-I', SRC_DIR,
    ]
    cmd += [os.path.join(SRC_DIR, c) for c in FRISO_C]
    cmd += [os.path.join(SHIM_DIR, 'shim.c'),
            os.path.join(SHIM_DIR, 'luna_glue.c')]
    cmd += [
        '-Wl,--no-entry',
        '-Wl,--initial-memory=50331648',      # 48 MiB
        '-Wl,--max-memory=268435456',        # 256 MiB
        '-Wl,-z,stack-size=524288',          # 512 KiB
    ]
    for name in EXPORTS:
        cmd.append('-Wl,--export=' + name)
    cmd += ['-o', WASM_OUT]
    print('[1/3] compiling luna.wasm ...')
    r = subprocess.run(cmd, capture_output=True, text=True,
                       encoding='utf-8', errors='replace')
    if r.stdout:
        print(r.stdout)
    if r.returncode != 0:
        print(r.stderr)
        raise SystemExit('wasm compile failed')
    print('      ok  %.1f KiB' % (os.path.getsize(WASM_OUT) / 1024.0))


def build_pack():
    """LDIC archive containing friso.ini, friso.lex.ini and every .lex
    referenced by friso.lex.ini."""
    os.makedirs(ASSET_DIR, exist_ok=True)

    # patched ini: lex_dir -> virtual /d/
    with open(os.path.join(FRISO_ROOT, 'wordfreq.ini'), 'r',
              encoding='utf-8') as f:
        ini_text = f.read()
    ini_text = re.sub(r'friso\.lex_dir\s*=.*', 'friso.lex_dir = /d/',
                      ini_text)
    members = [('friso.ini', ini_text.encode('utf-8'))]

    with open(os.path.join(DICT_DIR, 'friso.lex.ini'), 'rb') as f:
        lex_ini = f.read()
    members.append(('friso.lex.ini', lex_ini))

    names = re.findall(rb'([A-Za-z0-9_.\-]+\.lex)', lex_ini)
    seen = set()
    for raw in names:
        name = raw.decode('ascii')
        if name in seen:
            continue
        seen.add(name)
        with open(os.path.join(DICT_DIR, name), 'rb') as f:
            members.append((name, f.read()))

    blob = b'LDIC' + struct.pack('<I', len(members))
    for name, data in members:
        nb = name.encode('ascii')
        blob += struct.pack('<I', len(nb)) + nb
        blob += struct.pack('<I', len(data)) + data
    with open(PACK_OUT, 'wb') as f:
        f.write(blob)

    total = sum(len(d) for _, d in members)
    print('[2/3] dict.pack: %d files, %.1f KiB raw, %.1f KiB packed'
          % (len(members), total / 1024.0, len(blob) / 1024.0))


def build_assets_js():
    with open(WASM_OUT, 'rb') as f:
        wasm_b64 = base64.b64encode(f.read()).decode('ascii')
    with open(PACK_OUT, 'rb') as f:
        dict_b64 = base64.b64encode(f.read()).decode('ascii')
    with open(MODEL_BIN, 'rb') as f:
        model_b64 = base64.b64encode(f.read()).decode('ascii')

    js = (
        '/* Generated by luna/build.py - do not edit. */\n'
        '/* Base64 payloads: wasm shim + MMSEG dict + neutral3322 model. */\n'
        '(function () {\n'
        '  var A = {\n'
        '    wasm: "%s",\n'
        '    dict: "%s",\n'
        '    m3322: "%s"\n'
        '  };\n'
        '  (window.__LUNA_ASSETS__ = window.__LUNA_ASSETS__ || {});\n'
        '  Object.assign(window.__LUNA_ASSETS__, A);\n'
        '  if (typeof module !== "undefined" && module.exports) {\n'
        '    module.exports = A;\n'
        '  }\n'
        '  document.dispatchEvent(new CustomEvent("luna-assets-ready"));\n'
        '})();\n'
        % (wasm_b64, dict_b64, model_b64)
    )
    with open(JS_OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(js)
    print('[3/3] luna-assets.js: %.1f KiB (base64)'
          % (os.path.getsize(JS_OUT) / 1024.0))


def build_gzip():
    """静态部署用预压文件（弱网友好：约省 70% 流量）。
       luna.js 在支持 DecompressionStream 的浏览器优先取 .gz，否则回落原文件。"""
    import gzip
    targets = [
        (PACK_OUT, PACK_OUT + '.gz'),
        (MODEL_BIN, MODEL_BIN + '.gz'),
    ]
    for src, dst in targets:
        with open(src, 'rb') as f:
            raw = f.read()
        with gzip.GzipFile(filename='', mode='wb', compresslevel=9,
                           mtime=0, fileobj=open(dst, 'wb')) as gz:
            gz.write(raw)
        print('  gzip %s: %.1f KiB -> %.1f KiB'
              % (os.path.basename(src), len(raw) / 1024.0,
                 os.path.getsize(dst) / 1024.0))


if __name__ == '__main__':
    build_wasm()
    build_pack()
    build_assets_js()
    build_gzip()
    print('done.')
